const dictionaries: Record<Lang, Record<Key, string>> = { en, ru };

let current = $state<Lang>(DEFAULT_LANG);

export const i18n = {
  get lang() {
    return current;
  },
  set lang(value: Lang) {
    current = value;
  },
};

/// Translates a key; `{name}` placeholders are filled from `vars`. Reactive: reads the current language.
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return dictionaries[current][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}
